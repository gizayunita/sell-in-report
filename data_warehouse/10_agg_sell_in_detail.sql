-- 10. AGG SELL IN DETAIL
CREATE OR REPLACE TABLE `sales_marts_som.agg_sell_in_detail` AS
SELECT
  created_on,
  sent_on,
  sales_type,
  sub_sales_type,
  channel_group,
  channel,
  sub_channel_group,
  region,
  area,
  province,
  city,
  customer_name,
  item_name,
  brand,
  category,
  sub_category,
  variant,
  product_name,
  type_of_item,
  product_type,
  SUM(quantity) AS quantity
FROM `sales_marts_som.fact_sell_in`
GROUP BY
  created_on,
  sent_on,
  sales_type,
  sub_sales_type,
  channel_group,
  channel,
  sub_channel_group,
  region,
  area,
  province,
  city,
  customer_name,
  item_name,
  brand,
  category,
  sub_category,
  variant,
  product_name,
  type_of_item,
  product_type
